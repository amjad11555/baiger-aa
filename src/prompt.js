import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

/**
 * ملفات المعرفة التي تدخل سياق الوكيل.
 *
 * ⛔ لا تُضِف هنا أي ملف داخلي:
 *    - knowledge/pricing-internal.md      (أسعار وحدود دنيا)
 *    - knowledge/sales-playbook-internal.md (خصومات وتقسيط وضمانات تعاقدية)
 * هذه للفريق البشري فقط. أي رقم يدخل سياق الوكيل قابل للتسريب مهما مُنع بالتعليمات.
 */
const KNOWLEDGE_FILES = [
  'knowledge/services.md',
  'knowledge/objections.md',
];

/**
 * تعليقات HTML في ملفات المعرفة هي ملاحظات تحرير موجّهة لمن يملأ الملف،
 * لا تعليمات للوكيل. وجودها في سياقه يجعله يقرأها كفجوات في معلوماته،
 * فيتردد ويقول "ما عندي معلومات". نحذفها قبل الحقن.
 */
function stripEditorialNotes(md) {
  return md
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n');
}

function loadKnowledge() {
  const parts = [];
  const missing = [];

  for (const rel of KNOWLEDGE_FILES) {
    try {
      const md = stripEditorialNotes(readFileSync(join(ROOT, rel), 'utf8'));
      parts.push(`=== ${rel} ===\n${md}`);
    } catch {
      missing.push(rel);
    }
  }

  if (missing.length) {
    console.warn(`[prompt] ملفات معرفة مفقودة: ${missing.join(', ')}`);
  }
  if (!parts.length) {
    return '(لم يتم العثور على أي ملف معرفة — الوكيل بلا مصدر حقيقة)';
  }
  return parts.join('\n\n');
}

